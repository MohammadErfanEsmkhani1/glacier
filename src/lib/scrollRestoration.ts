const STORAGE_PREFIX = 'glacier-scroll:v2:'
const RESTORE_FALLBACK_MS = 12000

function getStorageKey() {
  return STORAGE_PREFIX + window.location.pathname + window.location.search
}

function readSavedPosition(key: string) {
  try {
    const value = sessionStorage.getItem(key)
    if (value === null) return null
    const position = Number(value)
    return Number.isFinite(position) && position >= 0 ? position : null
  } catch {
    return null
  }
}

function writeSavedPosition(key: string, position: number) {
  try {
    sessionStorage.setItem(key, String(Math.max(0, Math.round(position))))
  } catch {
    // Session storage may be unavailable in private or restricted browsing.
  }
}

/**
 * Keeps the browser's native reload restoration enabled and adds a session
 * snapshot fallback for pages whose React content grows after first paint.
 */
export function installScrollRestoration() {
  const key = getStorageKey()
  const savedPosition = readSavedPosition(key)
  let restored = savedPosition === null || savedPosition === 0
  let userInteracted = false
  let saveTimer = 0
  let restoreTimer = 0
  let restoreFrame = 0
  let fallbackTimer = 0
  let mutationObserver: MutationObserver | null = null
  let resizeObserver: ResizeObserver | null = null
  let originalScrollBehavior = ''

  // Let the browser restore reload positions itself whenever possible.
  if ('scrollRestoration' in window.history) {
    window.history.scrollRestoration = 'auto'
  }

  const cleanupRestoreObservers = () => {
    mutationObserver?.disconnect()
    resizeObserver?.disconnect()
    mutationObserver = null
    resizeObserver = null
    window.clearTimeout(restoreTimer)
    window.clearTimeout(fallbackTimer)
    if (restoreFrame) window.cancelAnimationFrame(restoreFrame)
  }

  const savePositionNow = () => {
    writeSavedPosition(key, window.scrollY)
  }

  const savePosition = () => {
    if (!restored) return
    window.clearTimeout(saveTimer)
    saveTimer = window.setTimeout(savePositionNow, 140)
  }

  const finishRestoration = () => {
    if (restored) return
    restored = true
    cleanupRestoreObservers()
    document.documentElement.style.scrollBehavior = originalScrollBehavior
    savePositionNow()
  }

  const cancelForUserInput = () => {
    if (restored) return
    userInteracted = true
    finishRestoration()
  }

  const attemptRestore = () => {
    if (restored || userInteracted || savedPosition === null || savedPosition <= 0) return

    // Wait until the loading overlay is gone, not merely fading out.
    const loader = document.querySelector('.viewport-preloader')
    if (loader && !loader.classList.contains('is-leaving')) return

    const maxScroll = Math.max(0, document.documentElement.scrollHeight - window.innerHeight)
    const currentScroll = window.scrollY

    // Native browser restoration may already have placed us correctly.
    if (Math.abs(currentScroll - savedPosition) <= 3) {
      finishRestoration()
      return
    }

    // Do not issue a scroll while the document is shorter than the saved
    // location: browsers clamp it, losing the intended position.
    if (maxScroll + 3 < savedPosition) return

    originalScrollBehavior = document.documentElement.style.scrollBehavior
    document.documentElement.style.scrollBehavior = 'auto'
    window.scrollTo({ top: savedPosition, left: 0, behavior: 'instant' })

    window.requestAnimationFrame(() => {
      window.requestAnimationFrame(() => {
        if (Math.abs(window.scrollY - savedPosition) <= 4) {
          finishRestoration()
        } else {
          document.documentElement.style.scrollBehavior = originalScrollBehavior
        }
      })
    })
  }

  const scheduleRestore = () => {
    if (restored || userInteracted || restoreFrame) return
    restoreFrame = window.requestAnimationFrame(() => {
      restoreFrame = 0
      attemptRestore()
    })
  }

  const onUserScroll = () => {
    if (!restored && savedPosition !== null && savedPosition > 0) {
      // Ignore scroll events generated by the browser's own native restore.
      if (Math.abs(window.scrollY - savedPosition) <= 4) {
        finishRestoration()
        return
      }
    }
    savePosition()
  }

  const onPageHide = () => {
    window.clearTimeout(saveTimer)
    savePositionNow()
  }

  const onVisibilityChange = () => {
    if (document.visibilityState === 'hidden') onPageHide()
    else scheduleRestore()
  }

  const onPageShow = () => scheduleRestore()
  const onLoad = () => scheduleRestore()

  window.addEventListener('scroll', onUserScroll, { passive: true })
  window.addEventListener('pagehide', onPageHide)
  window.addEventListener('beforeunload', onPageHide)
  window.addEventListener('pageshow', onPageShow)
  window.addEventListener('load', onLoad)
  document.addEventListener('visibilitychange', onVisibilityChange)

  // If a person starts navigating before restoration completes, don't pull
  // the page back to the old position under their input.
  window.addEventListener('wheel', cancelForUserInput, { passive: true, once: true })
  window.addEventListener('touchstart', cancelForUserInput, { passive: true, once: true })
  window.addEventListener('pointerdown', cancelForUserInput, { passive: true, once: true })
  window.addEventListener('keydown', cancelForUserInput, { once: true })

  if (!restored) {
    mutationObserver = new MutationObserver(scheduleRestore)
    mutationObserver.observe(document.documentElement, {
      childList: true,
      subtree: true,
      attributes: true,
      attributeFilter: ['class'],
    })

    if (typeof ResizeObserver !== 'undefined') {
      resizeObserver = new ResizeObserver(scheduleRestore)
      resizeObserver.observe(document.documentElement)
      if (document.body) resizeObserver.observe(document.body)
    }

    // Also retry at a few milestones in case an observer misses a layout shift.
    ;[80, 250, 600, 1200, 2200, 4000].forEach((delay) => {
      window.setTimeout(scheduleRestore, delay)
    })
    restoreTimer = window.setTimeout(scheduleRestore, RESTORE_FALLBACK_MS)

    // If content genuinely became shorter, restore to the furthest reachable
    // position rather than leaving the user at the top.
    fallbackTimer = window.setTimeout(() => {
      if (restored || userInteracted || savedPosition === null) return
      const reachablePosition = Math.min(
        savedPosition,
        Math.max(0, document.documentElement.scrollHeight - window.innerHeight),
      )
      originalScrollBehavior = document.documentElement.style.scrollBehavior
      document.documentElement.style.scrollBehavior = 'auto'
      window.scrollTo({ top: reachablePosition, left: 0, behavior: 'instant' })
      window.requestAnimationFrame(() => {
        document.documentElement.style.scrollBehavior = originalScrollBehavior
        finishRestoration()
      })
    }, RESTORE_FALLBACK_MS + 500)
  }

  // A newly opened page has no previous scroll state to restore, so start
  // recording as soon as the user begins scrolling.
  return () => {
    window.clearTimeout(saveTimer)
    cleanupRestoreObservers()
    window.removeEventListener('scroll', onUserScroll)
    window.removeEventListener('pagehide', onPageHide)
    window.removeEventListener('beforeunload', onPageHide)
    window.removeEventListener('pageshow', onPageShow)
    window.removeEventListener('load', onLoad)
    document.removeEventListener('visibilitychange', onVisibilityChange)
    window.removeEventListener('wheel', cancelForUserInput)
    window.removeEventListener('touchstart', cancelForUserInput)
    window.removeEventListener('pointerdown', cancelForUserInput)
    window.removeEventListener('keydown', cancelForUserInput)
    document.documentElement.style.scrollBehavior = originalScrollBehavior
  }
}
